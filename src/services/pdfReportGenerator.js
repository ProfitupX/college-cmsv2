// ─────────────────────────────────────────────────────────────
// REPORT: Laboratory Marks Statement (Lab Marks & Attended Hours Only)
// Applicable for Theory-cum-Lab and Laboratory / Practical Subjects
// ─────────────────────────────────────────────────────────────
export const generateLaboratoryMarksOnlyPDF = async ({
  subject, classObj, staff, session, students,
  attendanceData = {}, labData = {}, internalExamData = {},
  totalHours = 0, labHours = 0, assessmentMode = 'internal1',
  targetPages = 'auto', user
}) => {
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageHeight = doc.internal.pageSize.getHeight();

  const title = `${subject?.code || ''} - Laboratory / Practical Marks Statement`;
  await drawCollegeHeader(doc, title, 'NAC/TLP-LAB.01', '01', '', '1 of 1');

  // Determine prescribed lab hours:
  let prescribedLabHours = parseInt(labHours || 0, 10);
  if (!prescribedLabHours || prescribedLabHours <= 0) {
    const rawTot = parseInt(totalHours || subject?.total_hours || 60, 10);
    const splits = getHourSplits(subject?.ltpc, subject?.type, rawTot);
    prescribedLabHours = splits.lab > 0 ? splits.lab : (subject?.type === 'Practical' ? 40 : 30);
  }

  let y = 46;
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  const staffName = staff?.name || subject?.faculty_name || subject?.staff_name || 'Faculty Staff';
  doc.text(`Year / Sem       : ${classObj?.year_label || 'II'} / ${classObj?.semester || '4'}`, 14, y);
  doc.text(`Dept                 : ${subject?.department || classObj?.department || 'IT'}`, 120, y);
  y += 5;
  doc.text(`Staff Name       : ${staffName}`, 14, y);
  doc.text(`Academic Year: 2026 - 2027`, 120, y);
  y += 5;
  doc.text(`Subject            : ${subject?.code} / ${subject?.name}`, 14, y);
  doc.text(`Total Lab Hrs  : ${prescribedLabHours} Hours`, 120, y);
  y += 5;
  doc.text(`Assessment     : ${assessmentMode === 'internal2' ? 'Internal Assessment 2' : 'Internal Assessment 1'}`, 14, y);
  doc.text(`Date                 : ${new Date().toLocaleDateString('en-GB')}`, 120, y);
  y += 7;

  // Table Headers:
  // 1.) Lab Attended Hours
  // 2.) Lab Marks (/100)
  const headRow = [
    'S.No',
    'Roll No',
    'Student Name',
    `Lab Attended\n(/ ${prescribedLabHours} Hrs)`,
    'Lab Marks\n(/ 100)',
    'Result\n(Pass / Fail)'
  ];

  const bodyRows = students.map((st, idx) => {
    let attendedHours = 0;
    if (labData[st.id]?.labAttendance !== undefined && labData[st.id]?.labAttendance !== null && labData[st.id]?.labAttendance !== '') {
      attendedHours = parseInt(labData[st.id].labAttendance, 10);
    } else if (attendanceData[st.id] !== undefined && attendanceData[st.id] !== null && attendanceData[st.id] !== '') {
      attendedHours = parseInt(attendanceData[st.id], 10);
    }
    const cleanHours = Math.min(attendedHours, prescribedLabHours);

    let rawLabMark = null;
    if (labData[st.id]?.labMark !== undefined && labData[st.id]?.labMark !== null && labData[st.id]?.labMark !== '') {
      rawLabMark = labData[st.id].labMark;
    } else if (internalExamData[st.id] !== undefined && internalExamData[st.id] !== null && internalExamData[st.id] !== '') {
      rawLabMark = internalExamData[st.id];
    }

    const numMark = parseFloat(rawLabMark);
    const isAbsent = isNaN(numMark) || rawLabMark === null || rawLabMark === '' || rawLabMark === 'AB';
    const markDisplay = isAbsent ? 'AB' : Math.round(numMark);
    const result = isAbsent ? 'AB' : (numMark >= 50 ? 'PASS' : 'FAIL');
    const cleanName = String(st.name || '').replace(/ð[^\s]*/g, '').trim();

    return [
      idx + 1,
      st.roll_no || st.rollNo || '-',
      cleanName,
      `${cleanHours} / ${prescribedLabHours}`,
      markDisplay,
      result
    ];
  });

  const footRow = [
    '',
    '',
    'MAX MARKS / CRITERIA',
    `${prescribedLabHours} Hrs`,
    '100',
    '>= 50 Pass'
  ];

  const colStyles = {
    0: { cellWidth: 12, halign: 'center' },
    1: { cellWidth: 32, halign: 'center' },
    2: { cellWidth: 70, halign: 'left' },
    3: { cellWidth: 26, halign: 'center' },
    4: { cellWidth: 26, halign: 'center' },
    5: { cellWidth: 24, halign: 'center' }
  };

  const sCount = students.length;
  let tableFontSize = 8;
  let tableCellPadding = 1.6;

  if (targetPages === '1_page') {
    tableFontSize = sCount > 55 ? 6.2 : (sCount > 40 ? 6.8 : 7.2);
    tableCellPadding = sCount > 55 ? 0.6 : (sCount > 40 ? 0.9 : 1.2);
  } else if (targetPages === '2_pages') {
    tableFontSize = 7.8;
    tableCellPadding = 2.0;
  } else if (targetPages === '3_pages') {
    tableFontSize = 8.5;
    tableCellPadding = 3.2;
  }

  autoTable(doc, {
    startY: y,
    head: [headRow],
    body: bodyRows,
    foot: [footRow],
    theme: 'grid',
    margin: { top: 15, bottom: 22, left: 10, right: 10 },
    styles: { fontSize: tableFontSize, cellPadding: tableCellPadding, halign: 'center', valign: 'middle' },
    headStyles: { fillColor: [14, 116, 144], textColor: [255, 255, 255], fontStyle: 'bold' },
    footStyles: { fillColor: [248, 250, 252], textColor: [0, 0, 0], fontStyle: 'bold' },
    columnStyles: colStyles
  });

  // Footer Signatures: Lab Faculty In-Charge & HOD pinned at bottom of final page
  let totalDocPages = doc.internal.getNumberOfPages();

  if (targetPages === '2_pages' && totalDocPages < 2) {
    doc.addPage();
  } else if (targetPages === '3_pages' && totalDocPages < 3) {
    while (doc.internal.getNumberOfPages() < 3) {
      doc.addPage();
    }
  }

  totalDocPages = doc.internal.getNumberOfPages();
  doc.setPage(totalDocPages);

  let sigY = pageHeight - 22;
  if (doc.lastAutoTable && doc.lastAutoTable.finalY && doc.internal.getCurrentPageInfo().pageNumber === totalDocPages) {
    if (doc.lastAutoTable.finalY + 14 > sigY) {
      if (targetPages === '1_page') {
        sigY = Math.min(pageHeight - 12, doc.lastAutoTable.finalY + 6);
      } else {
        doc.addPage();
        sigY = pageHeight - 22;
      }
    }
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(0, 0, 0);
  doc.text('LAB FACULTY IN-CHARGE', 25, sigY);
  doc.text('HOD', 165, sigY);

  const now = new Date();
  addFooterToAllPages(doc, now.toLocaleDateString('en-GB'), now.toLocaleTimeString('en-GB', { hour12: false }), user);
  doc.save(`${subject?.code}_Laboratory_Marks_Statement.pdf`);
};
