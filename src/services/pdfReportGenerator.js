// Helper to convert image URL/imported asset to base64 DataURL
const getImageDataUrl = (url) => {
  return new Promise((resolve) => {
    const img = new Image();
    img.crossOrigin = 'Anonymous';
    img.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = img.width;
      canvas.height = img.height;
      const ctx = canvas.getContext('2d');
      ctx.drawImage(img, 0, 0);
      resolve(canvas.toDataURL('image/jpeg'));
    };
    img.onerror = () => resolve(null);
    img.src = url;
  });
};

const formatExamDate = (d) => {
  if (!d) return '—';
  const parsed = new Date(d);
  if (isNaN(parsed.getTime())) return '—';
  return parsed.toLocaleDateString('en-GB'); // DD/MM/YYYY
};

const addFooterToAllPages = (doc, dateStr, timeStr, user) => {
  const pageCount = doc.internal.getNumberOfPages();
  const pageHeight = doc.internal.pageSize.getHeight();
  const pageWidth = doc.internal.pageSize.getWidth();
  const printedByName = user?.name ? `${user.name}${user.role ? ` (${user.role.toUpperCase()})` : ''}` : 'NSCET Mark Hub';
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    // Separation line above footer
    doc.setDrawColor(203, 213, 225);
    doc.setLineWidth(0.25);
    doc.line(10, pageHeight - 8.5, pageWidth - 10, pageHeight - 8.5);

    // Timestamp & user stamp (crisp, bold, dark slate)
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(30, 41, 59);
    doc.text(`Generated by: ${printedByName}  |  Date: ${dateStr}  |  Time: ${timeStr} (IST)  |  MarkHub NSCET`, 10, pageHeight - 4);

    // Page indicator
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(71, 85, 105);
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 10, pageHeight - 4, { align: 'right' });
  }
};

